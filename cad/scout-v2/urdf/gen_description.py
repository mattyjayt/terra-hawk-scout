#!/usr/bin/env python3
"""robot_params.json -> urdf/scout.urdf.xacro + urdf/scout.urdf (expanded, same numbers).

Usage:  python urdf/gen_description.py [params.json] [--outdir urdf] [--mesh-dir ../out/STL]

The checked-in URDF is generated: edit the params file (CAD owns out/robot_params.json) and
rerun, never hand-edit scout.urdf. Frames: REP-103 (base_footprint on the ground at the centre
of rotation, +X forward, +Y left, +Z up), metres / kg / radians.
"""
import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "sim"))
from scout_params import WHEELS, Params  # noqa: E402

COLORS = {"plate": "0.85 0.85 0.85 1", "motor": "0.89 0.75 0.27 1", "battery": "0.23 0.48 0.84 1",
          "lidar": "0.13 0.16 0.19 1", "pi5": "0.12 0.44 0.26 1", "default": "0.55 0.35 0.68 1"}
MOTOR_DEFAULT = {"stall_torque": 0.0785, "no_load_speed": 20.94}   # TT 1:48 @6 V (Adafruit 3777), see sim/motor_profiles.json


def f(x):
    return f"{x:.6g}"


def v3(v):
    return " ".join(f(x) for x in v)


def color_for(name):
    for k in COLORS:
        if k in name:
            return k
    return "default"


def inertial(m, com, I6):
    ixx, iyy, izz, ixy, ixz, iyz = I6
    return (f'    <inertial>\n      <origin xyz="{v3(com)}" rpy="0 0 0"/>\n      <mass value="{f(m)}"/>\n'
            f'      <inertia ixx="{f(ixx)}" ixy="{f(ixy)}" ixz="{f(ixz)}" iyy="{f(iyy)}" iyz="{f(iyz)}" izz="{f(izz)}"/>\n'
            f'    </inertial>\n')


def ledger(P, src):
    w = P.wheels
    return f"""<!--
  TerraHawk Scout v2 robot description - GENERATED by urdf/gen_description.py, do not hand-edit.
  Params: {src}  (version {P.version})

  DESIGN LEDGER
  - Frames: REP-103. base_footprint = ground plane at the centre of rotation (midpoint of the
    front and rear axles, on the centreline). +X forward (Elegoo servo / Dead Plate end), +Y left, +Z up.
  - Units: metres, kilograms, radians. Params file is already in this frame (no transform).
  - base_link: fixed above base_footprint at mean axle height z={f(P.axle_z)} m. Its inertial lumps every
    rigid chassis part in the params file ({len(P.chassis_links)} links, {P.chassis_mass:.3f} kg, parallel-axis theorem in sim/scout_params.py).
  - Wheels: 4 continuous joints wheel_<fl|fr|rl|rr>_joint, axis +Y on every wheel, so a positive
    joint velocity rolls the robot forward on BOTH sides (no mirrored sign). Radius {f(P.wheel_radius)} m,
    width {f(P.wheel_width)} m, track {f(P.track)} m, wheelbase {f(P.wheelbase)} m.
    Wheel visual/collision cylinder is rotated rpy=(pi/2,0,0) so its axis lies along the joint axis.
  - Limits: effort = TT stall torque {MOTOR_DEFAULT['stall_torque']} N m, velocity = no-load {MOTOR_DEFAULT['no_load_speed']} rad/s
    (TT 1:48 @ 6 V, Adafruit 3777 datasheet) - replace when the encoder motor is chosen.
  - Sensors (fixed joints from base_link): laser_link at the scan plane (z={f(P.sensors['laser']['pos'][2])} above ground),
    camera_link (X forward body convention) + camera_optical_link (REP-103 optical: z forward, x right,
    y down; rpy = -pi/2 0 -pi/2), imu_link, ultrasonic_link (X = sensing direction).
  - Collision: boxes from each params link bbox (plates, motors, boards, LiDAR), cylinders for wheels.
  - Assumptions: see the params file's *_source fields. Fallback v1 numbers are marked there.
-->
"""


def body_boxes(P, base_z, indent="    "):
    vis, col = [], []
    for name, c, s in P.boxes():
        cc = [c[0], c[1], c[2] - base_z]
        mat = color_for(name)
        vis.append(f'{indent}<visual name="{name}">\n{indent}  <origin xyz="{v3(cc)}" rpy="0 0 0"/>\n'
                   f'{indent}  <geometry><box size="{v3(s)}"/></geometry>\n{indent}  <material name="{mat}"/>\n{indent}</visual>\n')
        col.append(f'{indent}<collision name="{name}">\n{indent}  <origin xyz="{v3(cc)}" rpy="0 0 0"/>\n'
                   f'{indent}  <geometry><box size="{v3(s)}"/></geometry>\n{indent}</collision>\n')
    return "".join(vis) + "".join(col)


def materials():
    return "".join(f'  <material name="{k}"><color rgba="{v}"/></material>\n' for k, v in COLORS.items()) + \
        '  <material name="rubber"><color rgba="0.1 0.1 0.1 1"/></material>\n'


SENSOR_LINKS = (("laser", "laser_link"), ("camera", "camera_link"), ("imu", "imu_link"), ("ultrasonic", "ultrasonic_link"))

ROS2_CONTROL_SKETCH = """
  <!-- ros2_control sketch (NOT controller code). Hardware plugin name is a placeholder for the
       ESP32 micro-ROS / serial bridge. Skid-steer runs on diff_drive_controller with two wheels
       per side:
       controller_manager:
         ros__parameters: {update_rate: 50, diff_drive_controller: {type: diff_drive_controller/DiffDriveController}}
       diff_drive_controller:
         ros__parameters:
           left_wheel_names:  [wheel_fl_joint, wheel_rl_joint]
           right_wheel_names: [wheel_fr_joint, wheel_rr_joint]
           wheel_separation: TRACK            # nominal; skid-steer needs wheel_separation_multiplier ~ sim/results.json spin.effective_track_ratio
           wheel_radius: RADIUS
           wheel_separation_multiplier: 1.0   # calibrate (see docs/sim-round1.md)
           base_frame_id: base_footprint
           odom_frame_id: odom
           enable_odom_tf: false              # robot_localization EKF publishes odom->base_footprint
           linear.x.max_velocity: 0.3
           angular.z.max_velocity: 1.0
           cmd_vel_timeout: 0.3               # REQ-SCOUT-002
  -->
"""


def ros2_control_xacro():
    joints = "".join(f"""      <joint name="wheel_{k}_joint">
        <command_interface name="velocity"><param name="min">-${{wheel_max_vel}}</param><param name="max">${{wheel_max_vel}}</param></command_interface>
        <state_interface name="position"/>
        <state_interface name="velocity"/>
      </joint>
""" for k in WHEELS)
    return f"""  <xacro:if value="$(arg use_ros2_control)">
    <ros2_control name="ScoutSystem" type="system">
      <hardware>
        <plugin>scout_hardware/ScoutEsp32System</plugin>  <!-- placeholder, not implemented -->
      </hardware>
{joints}    </ros2_control>
  </xacro:if>
"""


def build_urdf(P, src, xacro=False, mesh_dir=None):
    bz = P.axle_z
    L = []
    if xacro:
        L.append('<?xml version="1.0"?>\n')
        L.append(ledger(P, src))
        L.append('<robot name="scout" xmlns:xacro="http://www.ros.org/wiki/xacro">\n')
        L.append('  <xacro:arg name="use_ros2_control" default="false"/>\n  <xacro:arg name="payload" default="false"/>\n')
        L.append(f'  <xacro:property name="wheel_radius" value="{f(P.wheel_radius)}"/>\n'
                 f'  <xacro:property name="wheel_width" value="{f(P.wheel_width)}"/>\n'
                 f'  <xacro:property name="axle_z" value="{f(bz)}"/>\n'
                 f'  <xacro:property name="wheel_effort" value="{MOTOR_DEFAULT["stall_torque"]}"/>\n'
                 f'  <xacro:property name="wheel_max_vel" value="{MOTOR_DEFAULT["no_load_speed"]}"/>\n')
        w = P.wheels["fl"]
        r, wd, m = w["radius"], w["width"], w["mass"]
        L.append(f"""  <xacro:macro name="wheel" params="key x y z mass ixx iyy izz">
    <link name="wheel_${{key}}">
      <inertial>
        <origin xyz="0 0 0" rpy="0 0 0"/>
        <mass value="${{mass}}"/>
        <inertia ixx="${{ixx}}" ixy="0" ixz="0" iyy="${{iyy}}" iyz="0" izz="${{izz}}"/>
      </inertial>
      <visual>
        <origin xyz="0 0 0" rpy="${{pi/2}} 0 0"/>
        <geometry><cylinder radius="${{wheel_radius}}" length="${{wheel_width}}"/></geometry>
        <material name="rubber"/>
      </visual>
      <collision>
        <origin xyz="0 0 0" rpy="${{pi/2}} 0 0"/>
        <geometry><cylinder radius="${{wheel_radius}}" length="${{wheel_width}}"/></geometry>
      </collision>
    </link>
    <joint name="wheel_${{key}}_joint" type="continuous">
      <origin xyz="${{x}} ${{y}} ${{z - axle_z}}" rpy="0 0 0"/>
      <parent link="base_link"/>
      <child link="wheel_${{key}}"/>
      <axis xyz="0 1 0"/>
      <limit effort="${{wheel_effort}}" velocity="${{wheel_max_vel}}"/>
      <dynamics damping="0.0" friction="0.0"/>
    </joint>
  </xacro:macro>
""")
    else:
        L.append('<?xml version="1.0"?>\n')
        L.append(ledger(P, src))
        L.append('<robot name="scout">\n')
    L.append(materials())
    L.append('  <link name="base_footprint"/>\n')
    L.append(f'  <joint name="base_footprint_joint" type="fixed">\n    <origin xyz="0 0 {f(bz)}" rpy="0 0 0"/>\n'
             '    <parent link="base_footprint"/>\n    <child link="base_link"/>\n  </joint>\n')
    com = [P.chassis_com[0], P.chassis_com[1], P.chassis_com[2] - bz]
    L.append('  <link name="base_link">\n' + inertial(P.chassis_mass, com, P.chassis_inertia6()) + body_boxes(P, bz) + '  </link>\n')
    for k in WHEELS:
        w = P.wheels[k]
        I = w["inertia"]
        if xacro:
            L.append(f'  <xacro:wheel key="{k}" x="{f(w["pos"][0])}" y="{f(w["pos"][1])}" z="{f(w["pos"][2])}" '
                     f'mass="{f(w["mass"])}" ixx="{f(I[0])}" iyy="{f(I[1])}" izz="{f(I[2])}"/>\n')
            continue
        geo = f'<cylinder radius="{f(w["radius"])}" length="{f(w["width"])}"/>'
        rot = f'{f(math.pi / 2)} 0 0'
        L.append(f'  <link name="wheel_{k}">\n' + inertial(w["mass"], [0, 0, 0], I) +
                 f'    <visual>\n      <origin xyz="0 0 0" rpy="{rot}"/>\n      <geometry>{geo}</geometry>\n      <material name="rubber"/>\n    </visual>\n'
                 f'    <collision>\n      <origin xyz="0 0 0" rpy="{rot}"/>\n      <geometry>{geo}</geometry>\n    </collision>\n  </link>\n')
        L.append(f'  <joint name="wheel_{k}_joint" type="continuous">\n    <origin xyz="{v3([w["pos"][0], w["pos"][1], w["pos"][2] - bz])}" rpy="0 0 0"/>\n'
                 f'    <parent link="base_link"/>\n    <child link="wheel_{k}"/>\n    <axis xyz="0 1 0"/>\n'
                 f'    <limit effort="{MOTOR_DEFAULT["stall_torque"]}" velocity="{MOTOR_DEFAULT["no_load_speed"]}"/>\n'
                 '    <dynamics damping="0.0" friction="0.0"/>\n  </joint>\n')
    for key, link in SENSOR_LINKS:
        s = P.sensors.get(key)
        if not s:
            continue
        pos = [s["pos"][0], s["pos"][1], s["pos"][2] - bz]
        L.append(f'  <link name="{link}"/>\n  <joint name="{link[:-5]}_joint" type="fixed">\n'
                 f'    <origin xyz="{v3(pos)}" rpy="{v3(s.get("rpy", [0, 0, 0]))}"/>\n'
                 f'    <parent link="base_link"/>\n    <child link="{link}"/>\n  </joint>\n')
        if key == "camera":
            L.append('  <link name="camera_optical_link"/>\n  <joint name="camera_optical_joint" type="fixed">\n'
                     f'    <origin xyz="0 0 0" rpy="{f(-math.pi / 2)} 0 {f(-math.pi / 2)}"/>\n'
                     '    <parent link="camera_link"/>\n    <child link="camera_optical_link"/>\n  </joint>\n')
    pl = P.payload
    pl_block = (f'  <link name="payload">\n' +
                inertial(pl["mass"], [0, 0, 0], [pl["mass"] / 12 * (pl["size"][1]**2 + pl["size"][2]**2),
                                                  pl["mass"] / 12 * (pl["size"][0]**2 + pl["size"][2]**2),
                                                  pl["mass"] / 12 * (pl["size"][0]**2 + pl["size"][1]**2), 0, 0, 0]) +
                f'    <visual>\n      <geometry><box size="{v3(pl["size"])}"/></geometry>\n      <material name="default"/>\n    </visual>\n  </link>\n'
                f'  <joint name="payload_joint" type="fixed">\n    <origin xyz="{v3([pl["com"][0], pl["com"][1], pl["com"][2] - bz])}" rpy="0 0 0"/>\n'
                '    <parent link="base_link"/>\n    <child link="payload"/>\n  </joint>\n')
    if xacro:
        L.append('  <xacro:if value="$(arg payload)">\n' + pl_block + '  </xacro:if>\n')
        L.append(ROS2_CONTROL_SKETCH.replace("TRACK", f(P.track)).replace("RADIUS", f(P.wheel_radius)))
        L.append(ros2_control_xacro())
    else:
        L.append('  <!-- payload (300 g) omitted here; xacro arg payload:=true adds it -->\n')
        L.append(ROS2_CONTROL_SKETCH.replace("TRACK", f(P.track)).replace("RADIUS", f(P.wheel_radius)))
    L.append('</robot>\n')
    return "".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("params", nargs="?", default=None)
    ap.add_argument("--outdir", default=str(HERE))
    a = ap.parse_args()
    src = a.params or (ROOT / "out" / "robot_params.json")
    if not Path(src).exists():
        src = ROOT / "sim" / "params_v1_fallback.json"
    P = Params(src)
    out = Path(a.outdir)
    rel = Path(src).resolve().relative_to(ROOT) if str(Path(src).resolve()).startswith(str(ROOT)) else src
    (out / "scout.urdf.xacro").write_text(build_urdf(P, rel, xacro=True))
    (out / "scout.urdf").write_text(build_urdf(P, rel, xacro=False))
    print(json.dumps({"params": str(rel), "total_mass": round(P.total_mass, 4), "chassis_mass": round(P.chassis_mass, 4),
                      "chassis_com": [round(x, 4) for x in P.chassis_com], "track": P.track, "wheelbase": P.wheelbase}))


if __name__ == "__main__":
    main()
